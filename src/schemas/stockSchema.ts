import { z } from 'zod';

export const StockSummarySchema = z.object({
  symbol: z.string(),
  companyName: z.string(),
  exchange: z.enum(['HOSE', 'HNX', 'UPCOM']),
  sector: z.string(),
  price: z.number(),
  change: z.number(),
  changePercent: z.number(),
  volume: z.number(),
  tradingValue: z.number(),
  high: z.number().optional(),
  low: z.number().optional(),
  open: z.number().optional(),
  close: z.number().optional(),
  ceiling: z.number().optional(),
  floor: z.number().optional(),
  reference: z.number().optional(),
  rsi: z.number().nullable().optional(),
  pe: z.number().nullable().optional(),
  pb: z.number().nullable().optional(),
  roe: z.number().nullable().optional(),
  eps: z.number().nullable().optional(),
  marketCap: z.number().nullable().optional(),
  fairValue: z.number().nullable().optional(),
  upside: z.number().nullable().optional(),
  aiScore: z.number(),
  trend: z.enum(['UPTREND', 'DOWNTREND', 'SIDEWAY']),
  signal: z.enum(['BUY', 'SELL', 'HOLD']),
  isVN30: z.boolean().optional(),
  sparkline: z.array(z.number()).optional(),
});

export const IndexDataSchema = z.object({
  symbol: z.string(),
  displayName: z.string(),
  value: z.number(),
  change: z.number(),
  changePercent: z.number(),
  totalVolume: z.number(),
  totalValue: z.number(),
  advances: z.number(),
  declines: z.number(),
  unchanged: z.number(),
  ceilings: z.number(),
  floors: z.number(),
  status: z.string(),
  sparkline: z.array(z.number()).optional(),
  isDemo: z.boolean().optional(),
});

export const SectorHeatmapItemSchema = z.object({
  id: z.string(),
  name: z.string(),
  code: z.string(),
  changePercent: z.number(),
  totalValue: z.number(),
  stockCount: z.number(),
  advances: z.number(),
  declines: z.number(),
  unchanged: z.number(),
  topStock: z.string(),
  marketCapPercent: z.number().optional(),
});
